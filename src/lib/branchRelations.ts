/**
 * 今日日支对用户日支的关系（§2.3）。
 * ★ 入参 chart.allZhi 必须含【全四支】——并见时按局取用，不只看日支。
 *
 * 默认优先级（无并见）：同 → 冲 → 合 → 刑 → 害 → 无
 *
 * ★★ 两个真实重叠（144 组合里仅此两处）：
 *
 *   ① 巳申：既合又刑（六合＋无恩之刑）
 *      古法立场：两者同时存在，古籍不分先后。
 *        · 隋·萧吉《五行大义·论刑》：「六合是吉，而巳申相克者何……还相雠，故以为刑也。」
 *        · 晋·郭璞《郭氏元经》：「巳刑申者……所生之处反相刑而无恩，故曰无恩刑。」
 *          （申金生于巳，反被巳火所克 —— 受恩之处反生怨，故名无恩）
 *      ★ 我方系经【二手来源】核对上述两段原文，未取得原书影印 ——
 *        披露文案写「据《五行大义·论刑》」即可，不得声称「已核原书」（§8.6.2）。
 *
 *      产品取值规则（并见时取一个主导；依据层级＝【产品设定】，不得标古法）：
 *        局含 亥 或 子（水气得力） → 以「合」为主导
 *        局含 寅 或 午（火源得力） → 以「刑」为主导
 *        两者皆无 / 两者皆有       → 以「合」为主导（保守：合较温和，无恩之刑更重）
 *      「看局取用」这一实践属【通行做法】，我方未见古籍明文。
 *      ★ 同一天、不同局 → 可能得不同主导 —— 这正是「个性化」该有的样子。
 *
 *   ② 寅巳：既刑又害
 *      产品取【刑】（三刑较重、六害较隐；本产品不判轻重，只取一个主关系）。
 *      依据层级＝【产品设定】——古籍对「刑害并见孰为主」未见明确条件。
 */
export function dayBranchRelation(
  todayZhi: Zhi,
  chart: { dayZhi: Zhi; allZhi: readonly Zhi[] }
): BranchRelation {
  const { dayZhi, allZhi } = chart
  // 同支
  if (todayZhi === dayZhi) return '同'
  // 六冲
  if (LIU_CHONG[todayZhi] === dayZhi) return '冲'

  const isHe = LIU_HE[todayZhi] === dayZhi
  const isXing = XIANG_XING[todayZhi].includes(dayZhi)
  const isHai = LIU_HAI[todayZhi] === dayZhi

  // ① 巳申：既合又刑 → 看局取主导
  if (isHe && isXing) {
    const hasHaiZi = allZhi.some((z) => z === '亥' || z === '子')
    const hasYinWu = allZhi.some((z) => z === '寅' || z === '午')
    if (hasHaiZi && !hasYinWu) return '合'
    if (hasYinWu && !hasHaiZi) return '刑'
    return '合' // 皆无 / 皆有 → 合（保守）
  }
  // ② 寅巳：既刑又害 → 取刑
  if (isXing && isHai) return '刑'

  if (isHe) return '合'
  if (isXing) return '刑'
  if (isHai) return '害'
  return '无'
}
